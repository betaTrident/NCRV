import { AxeBuilder } from "@axe-core/playwright"
import { expect, test } from "@playwright/test"
import { DateTime } from "luxon"
import { signUpEmployee, uniqueEmail } from "./support/account"

test("employee shiftbook: empty, saved, TBD, filters, periods, settings and return context", async ({ page }, testInfo) => {
  test.setTimeout(180_000)
  await page.emulateMedia({ reducedMotion: "reduce" })
  const today = DateTime.now().setZone("Asia/Manila").toISODate()!
  const tomorrow = DateTime.fromISO(today).plus({days:1}).toISODate()!
  await signUpEmployee(page, { name: "Local redesign employee", email: uniqueEmail("workspace"), monthlyBasicSalary: "34800" })
  await expect(page.getByText("This calendar month", {exact:true})).toBeVisible()
  await expect(page.getByText("Your nights will take shape here")).toBeVisible()
  await page.goto("/records")
  await expect(page.getByRole("heading", {name:"Your shiftbook starts here"})).toBeVisible()
  await page.goto("/shift/new")
  await page.getByLabel("Work date").fill(today)
  await page.getByLabel("Shift start").fill("21:00")
  await page.getByLabel("Shift end").fill("06:00")
  await page.getByRole("button", {name:"Calculate shift"}).click()
  await page.getByRole("button", {name:"Save entry"}).click()
  await expect(page.getByRole("status").filter({hasText:"Saved privately"})).toBeVisible()
  await page.goto("/")
  await expect(page.getByRole("region", {name:"Total ND hours"})).toContainText("7.00 hrs")
  await page.waitForLoadState("networkidle")
  await page.screenshot({path:testInfo.outputPath("overview.png"), fullPage:true})
  await page.goto("/records?range=month")
  await expect(page.getByText("1 saved shifts", {exact:true})).toBeVisible()
  await page.getByRole("link", {name:/View record for/}).filter({visible:true}).click()
  await expect(page.getByRole("heading", {name:DateTime.fromISO(today).toFormat("MMMM d, yyyy")})).toBeVisible()
  await page.getByRole("link", {name:"Back to records"}).click()
  await expect(page).toHaveURL(/range=month/)
  await page.waitForLoadState("networkidle")
  await page.screenshot({path:testInfo.outputPath("records.png"), fullPage:true})
  await page.goto("/records?range=custom&from=2001-01-01&to=2001-01-02")
  await expect(page.getByRole("heading", {name:"No shifts in this range"})).toBeVisible()
  await page.goto("/records?range=period")
  await expect(page.getByRole("heading", {name:"No payroll period yet"})).toBeVisible()
  await page.goto("/calendar?date="+today)
  await page.getByText("Manage personal periods and holiday notes", {exact:true}).click()
  await page.getByLabel("Period start").fill(today)
  await page.getByLabel("Period end").fill(tomorrow)
  await page.getByRole("button", {name:"Add payroll period",exact:true}).click()
  await expect(page.getByRole("status").filter({hasText:"Saved"})).toBeVisible()
  await expect(page.getByLabel("Period start")).toHaveValue("")
  await page.getByRole("button", {name:"Edit period",exact:true}).click()
  await expect(page.getByLabel("Period start")).toHaveValue(today)
  await page.getByLabel("Cutoff time").fill("23:30")
  await page.getByRole("button", {name:"Save period changes"}).click()
  await expect(page.getByText(/Cutoff 11:30 PM/)).toBeVisible()
  await page.getByRole("button", {name:"Today",exact:true}).click()
  await page.getByRole("button", {name:"Open details for "+today,exact:true}).filter({visible:true}).click()
  await page.getByRole("dialog").getByRole("link", {name:"Open record"}).click()
  await page.getByRole("link", {name:"Back to calendar"}).click()
  await expect(page.getByRole("dialog")).toBeVisible()
  await page.keyboard.press("Escape")
  await page.waitForLoadState("networkidle")
  await page.screenshot({path:testInfo.outputPath("calendar.png"), fullPage:true})
  await page.goto("/settings")
  await expect(page.getByRole("heading", {name:"ADP code explorer"})).toBeHidden()
  await page.getByLabel("Name", {exact:true}).fill("Updated local employee")
  await page.getByLabel("Monthly basic salary", {exact:true}).fill("invalid")
  await page.getByRole("button", {name:"Save profile"}).click()
  await expect(page.getByLabel("Name", {exact:true})).toHaveValue("Updated local employee")
  await expect(page.getByLabel("Monthly basic salary", {exact:true})).toHaveValue("invalid")
  await page.getByLabel("Monthly basic salary", {exact:true}).fill("35000")
  await page.getByRole("button", {name:"Save profile"}).click()
  await expect(page.getByRole("status").filter({hasText:"Saved"})).toBeVisible()
  await page.getByLabel("ND start",{exact:true}).fill("21:30")
  await page.getByRole("button", {name:"Save computation"}).click()
  await page.reload()
  await expect(page.getByLabel("Name", {exact:true})).toHaveValue("Updated local employee")
  await expect(page.getByLabel("ND start",{exact:true})).toHaveValue("21:30")
  await page.waitForLoadState("networkidle")
  await page.screenshot({path:testInfo.outputPath("settings.png"), fullPage:true})
  for (const route of ["/", "/records", "/calendar", "/settings"]) {
    await page.locator(`nav[aria-label="Primary"] a[href="${route}"]:not([aria-label])`).filter({visible:true}).click()
    await expect(page).toHaveURL(new RegExp(route === "/" ? "/$" : route + "$"))
    await expect(page.locator("h1")).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.waitForLoadState("networkidle")
    if (route === "/") await expect(page.getByRole("region", {name:"Known estimate"})).toContainText("140.00")
    const axe = await new AxeBuilder({page}).analyze()
    expect(axe.violations.filter(item => item.impact === "serious" || item.impact === "critical")).toEqual([])
  }
})

test("all unresolved amounts stay TBD with no known zero", async ({page}) => {
  await page.emulateMedia({ reducedMotion: "reduce" })
  await signUpEmployee(page, {name:"Local TBD employee", email:uniqueEmail("workspace-tbd")})
  await page.goto("/shift/new")
  await page.getByLabel("Work date").fill(DateTime.now().setZone("Asia/Manila").toISODate()!)
  await page.getByLabel("Shift start").fill("21:00")
  await page.getByLabel("Shift end").fill("06:00")
  await page.getByRole("button", {name:"Calculate shift"}).click()
  await page.getByRole("button", {name:"Save entry"}).click()
  await expect(page.getByRole("status").filter({hasText:"Saved privately"})).toBeVisible()
  await page.goto("/")
  await expect(page.getByRole("region", {name:"Known estimate"})).toContainText("TBD")
  await expect(page.getByRole("region", {name:"Known estimate"})).not.toContainText("0.00")
})
